    public static IReadOnlyList<Credential> List => _cachedList ??= DecryptCredentials();

    private static IReadOnlyList<Credential> DecryptCredentials()
    {
        var result = new List<Credential>();

        foreach (var encrypted in EncryptedCredentials)
        {
            try
            {
                var decrypted = CredentialProtector.Unprotect(encrypted);
                var parts = decrypted.Split(':', 2);
                if (parts.Length == 2)
                {
                    result.Add(new Credential(parts[0], parts[1]));
                }
            }
            catch
            {
                // Пропускаем некорректные данные
            }
        }

        return result;
    }
